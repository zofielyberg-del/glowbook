const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
    const [language, setLanguage] = useState<Language>('Svenska');
    const [currency, setCurrency] = useState<string>('SEK');

    useEffect(() => {
        // 1. Try to load specifically saved language first
        const savedLang = localStorage.getItem('glowbook_language');
        if (savedLang) {
            setLanguage(savedLang as Language);
            return;
        }

        // 2. Fallback to salon data if available
        const savedSalon = localStorage.getItem('glowbook_salon');
        if (savedSalon) {
            const data = JSON.parse(savedSalon);
            if (data.country) {
                const countryData = NORDIC_COUNTRIES.find(c => c.name === data.country);
                if (countryData) {
                    setLanguage(countryData.language as Language);
                    setCurrency(countryData.currency);
                    return;
                }
            }
        }

        // 3. Fallback to browser language
        const browserLang = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : '';
        if (browserLang.includes('no')) setLanguage('Norska');
        else if (browserLang.includes('da')) setLanguage('Danska');
        else if (browserLang.includes('fi')) setLanguage('Finska');
        else if (browserLang.includes('is')) setLanguage('Isländska');
        else setLanguage('Svenska');
    }, []);

    // Persist language changes
    useEffect(() => {
        localStorage.setItem('glowbook_language', language);
    }, [language]);

    useEffect(() => {
        if (language === 'English') {
            setCurrency('EUR');
            return;
        }
        const matchingCountry = NORDIC_COUNTRIES.find(c => c.language === language);
        if (matchingCountry) {
            setCurrency(matchingCountry.currency);
        } else {
            setCurrency('EUR');
        }
    }, [language]);

    const t = (key: string) => {
        return translations[language]?.[key] || translations['English']?.[key] || translations['Svenska']?.[key] || key;
    };

    return (
        <LanguageContext.Provider value={{ language, setLanguage, currency, setCurrency, t }}>
            {children}
        </LanguageContext.Provider>
    );
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
}
