// Helper to get a country by code
export function getCountryByCode(code: string): NordicCountry | undefined {
    return NORDIC_COUNTRIES.find(c => c.code === code);
}

// Helper to get sorted municipalities for a country
export function getMunicipalities(countryCode: string): string[] {
    const country = getCountryByCode(countryCode);
    return country ? [...country.municipalities].sort((a, b) => a.localeCompare(b, 'sv')) : [];
}
